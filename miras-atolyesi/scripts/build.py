#!/usr/bin/env python3
"""Embed existing CSS, ES modules and original images in a portable HTML entry.

This small packager only accepts the project's existing, named relative imports.
It is not a general JavaScript compiler; unsupported imports fail explicitly.
"""
import argparse
import base64
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
MODULES = ('src/lexicon.js', 'src/text-guard.js', 'src/content.js', 'src/rules.js', 'src/game.js')
IMPORT = re.compile(r"^import \{ ([\w, ]+) \} from '(\./[\w.-]+\.js)';$", re.MULTILINE)
IMAGE_NAME = re.compile(r'[\w .-]+\.(png|jpe?g|webp)', re.IGNORECASE)


def pack_modules(root):
    processed = set()
    chunks = []
    for relative in MODULES:
        file = root / relative
        source = file.read_text(encoding='utf-8')
        for match in IMPORT.finditer(source):
            dependency = (file.parent / match[2]).resolve()
            if dependency not in processed:
                raise ValueError(f'{relative}: desteklenmeyen modül sırası veya import: {match[2]}')
        source = IMPORT.sub('', source)
        source = re.sub(r'^export (?=(?:const|function)\s)', '', source, flags=re.MULTILINE)
        if re.search(r'^\s*(import|export)\s', source, re.MULTILINE):
            raise ValueError(f'{relative}: desteklenmeyen import/export biçimi')
        chunks.append(f'// Source: {relative}\n{source}')
        processed.add(file.resolve())
    # All declarations retain their source order inside one private scope.
    return '\n(() => {\n"use strict";\n' + '\n'.join(chunks) + '\n})();\n'


def pack_images(root):
    asset_root = (root / 'assets').resolve()
    manifest = json.loads((asset_root / 'images.json').read_text(encoding='utf-8'))
    if not isinstance(manifest, dict) or set(manifest) != {'intro', 'game'}:
        raise ValueError('assets/images.json tam olarak intro ve game alanlarını içermeli.')
    packed = {}
    missing = []
    for key in ('intro', 'game'):
        filename = manifest[key]
        standard_name = 'giris.png' if key == 'intro' else 'giris_sonrasi.png'
        if filename is None and (asset_root / standard_name).is_file():
            filename = standard_name
        if filename is None:
            packed[key] = None
            missing.append(key)
            continue
        if not isinstance(filename, str) or not IMAGE_NAME.fullmatch(filename):
            raise ValueError(f'{key}: yalnızca assets içindeki PNG/JPEG/WebP dosya adı kullanılabilir.')
        image = (asset_root / filename).resolve()
        if image.parent != asset_root or not image.is_file():
            raise ValueError(f'{key}: özgün görsel bulunamadı: assets/{filename}')
        data = image.read_bytes()
        suffix = image.suffix.lower()
        if suffix == '.png' and data.startswith(b'\x89PNG\r\n\x1a\n'):
            mime = 'image/png'
        elif suffix in ('.jpg', '.jpeg') and data.startswith(b'\xff\xd8\xff'):
            mime = 'image/jpeg'
        elif suffix == '.webp' and data.startswith(b'RIFF') and data[8:12] == b'WEBP':
            mime = 'image/webp'
        else:
            raise ValueError(f'{key}: görsel uzantısı ve dosya imzası uyuşmuyor: {filename}')
        packed[key] = f'data:{mime};base64,{base64.b64encode(data).decode("ascii")}'
    return packed, missing


def build(root=ROOT, repo_entry=False):
    root = Path(root).resolve()
    template = (root / 'index.template.html').read_text(encoding='utf-8')
    css = (root / 'styles.css').read_text(encoding='utf-8')
    js = pack_modules(root)
    images, missing = pack_images(root)
    css_tag = '<link rel="stylesheet" href="styles.css">'
    js_tag = '<script type="module" src="src/game.js"></script>'
    if template.count(css_tag) != 1 or template.count(js_tag) != 1:
        raise ValueError('HTML şablonunun CSS/JavaScript girişleri beklenen biçimde değil.')
    if '</style' in css.lower() or '</script' in js.lower():
        raise ValueError('Kaynak dosyada HTML kapanış etiketi bulundu; güvenli gömme durduruldu.')
    html = template.replace(css_tag, f'<style id="game-styles">\n{css}\n</style>')
    config = json.dumps(images, ensure_ascii=True).replace('<', '\\u003c')
    html = html.replace(js_tag, f'<script id="embedded-assets" type="application/json">{config}</script>\n<script type="module" id="game-code">{js}</script>')
    html = html.replace('<!doctype html>', '<!doctype html>\n<!-- Generated by scripts/build.py; edit the original source files. -->', 1)
    output = root / 'index.html'
    output.write_text(html, encoding='utf-8')
    if repo_entry:
        # Only an explicit request may update the repository-level preview entry.
        package = root.parent / 'package.json'
        if not package.is_file() or json.loads(package.read_text()).get('name') != 'projeler':
            raise ValueError('--repo-entry yalnızca bu projenin depo kökünde kullanılabilir.')
        (root.parent / 'index.html').write_text(html, encoding='utf-8')
    return output, missing


def main():
    parser = argparse.ArgumentParser(description='Miras Atölyesi tek dosyalık önizleme çıktısı')
    parser.add_argument('--repo-entry', action='store_true')
    args = parser.parse_args()
    try:
        output, missing = build(repo_entry=args.repo_entry)
    except (ValueError, OSError) as error:
        print(f'Derleme durduruldu: {error}', file=sys.stderr)
        return 1
    print(f'HTML hazır: {output.name} (CSS ve JavaScript içeride)')
    if missing:
        print('Özgün görseller eksik: ' + ', '.join(missing) + '. Yerlerine yeni görsel üretilmedi.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
